    /** Runs one translated SQL statement; SQLCODE follows DB2 conventions (0, 100, -811, -305, negative on error). */
    public void sql(org.springframework.jdbc.core.JdbcTemplate jdbc, String sql, String[] in, String[] out) {
        if (jdbc == null) {
            setNum("SQLCODE", BigDecimal.valueOf(-1), false);
            sqlErrors.add("No database is configured for this service");
            return;
        }
        Object[] args = new Object[in.length];
        for (int i = 0; i < in.length; i++) args[i] = val(in[i]);
        try {
            if (out.length > 0) {
                List<Map<String, Object>> rows = jdbc.queryForList(sql, args);
                if (rows.isEmpty()) { setNum("SQLCODE", BigDecimal.valueOf(100), false); return; }
                if (rows.size() > 1) { setNum("SQLCODE", BigDecimal.valueOf(-811), false); return; }
                List<Object> cols = new ArrayList<>(rows.get(0).values());
                if (cols.size() != out.length) {
                    setNum("SQLCODE", BigDecimal.valueOf(-1), false);
                    sqlErrors.add("SELECT returned " + cols.size() + " column(s) for " + out.length + " host variable(s)");
                    return;
                }
                Object[] conv = new Object[out.length];
                for (int i = 0; i < out.length; i++) {       // convert everything before storing anything
                    Object v = cols.get(i);
                    if (v == null) { setNum("SQLCODE", BigDecimal.valueOf(-305), false); return; }
                    conv[i] = v instanceof Number ? new BigDecimal(v.toString()) : v.toString();
                    if (field(out[i]).kind == 'N' && !(conv[i] instanceof BigDecimal)) {
                        conv[i] = parseNumber(conv[i].toString(), out[i]);
                    }
                }
                for (int i = 0; i < out.length; i++) move(out[i], conv[i]);
                setNum("SQLCODE", BigDecimal.ZERO, false);
            } else {
                int n = jdbc.update(sql, args);
                String verb = sql.trim().toUpperCase();
                boolean noRow = n == 0 && (verb.startsWith("UPDATE") || verb.startsWith("DELETE"));
                setNum("SQLCODE", BigDecimal.valueOf(noRow ? 100 : 0), false);
            }
        } catch (RuntimeException e) {
            setNum("SQLCODE", BigDecimal.valueOf(-1), false);
            sqlErrors.add(e.getMessage());
        }
    }

