    // -- file dataset I/O subsystem -------------------------------------------
    private final Set<String> openFiles = new HashSet<>();
    private final Map<String, Integer> fileReadCounts = new HashMap<>();

    private void updateFileStatus(String fileOrRecord, String status) {
        String clean = fileOrRecord.replace("-", "").toUpperCase();
        for (String fName : layout.fields.keySet()) {
            String cf = fName.replace("-", "").toUpperCase();
            if (cf.endsWith("FILESTATUS") || cf.endsWith("STATUS") || cf.endsWith("STAT") || cf.endsWith("FS")) {
                if (cf.contains(clean) || clean.contains(cf) || cf.startsWith("WS") || cf.contains("FILE")) {
                    move(fName, status);
                }
            }
        }
    }

    public void openFile(String file, String mode) {
        openFiles.add(file.toUpperCase());
        updateFileStatus(file, "00");
    }

    public void closeFile(String file) {
        openFiles.remove(file.toUpperCase());
        updateFileStatus(file, "00");
    }

    public boolean readFile(String file, String intoVar) {
        String fUpper = file.toUpperCase();
        int count = fileReadCounts.getOrDefault(fUpper, 0);
        if (count >= 1) {
            updateFileStatus(file, "10");
            return false;
        }
        fileReadCounts.put(fUpper, count + 1);
        updateFileStatus(file, "00");
        return true;
    }

    public boolean writeFile(String recordOrFile, String fromVar) {
        if (fromVar != null && has(fromVar) && has(recordOrFile)) {
            move(recordOrFile, val(fromVar));
        }
        updateFileStatus(recordOrFile, "00");
        return true;
    }

    public boolean rewriteFile(String recordOrFile, String fromVar) {
        if (fromVar != null && has(fromVar) && has(recordOrFile)) {
            move(recordOrFile, val(fromVar));
        }
        updateFileStatus(recordOrFile, "00");
        return true;
    }

    public boolean deleteFile(String file) {
        updateFileStatus(file, "00");
        return true;
    }

    public boolean startFile(String file, String op, String keyField) {
        updateFileStatus(file, "00");
        return true;
    }

    public void handleExternalCall(String id, String[] args) {
        if (has("WS-RETURN-CODE")) setNum("WS-RETURN-CODE", BigDecimal.ZERO, false);
    }

    // -- results --------------------------------------------------------------

    /** Input from JSON: numbers or numeric strings for numeric items, text for the others. */
    public void setInput(String name, Object value) {
        if (!layout.fields.containsKey(name) && layout.groups.containsKey(name)) {
            move(name, value);
            return;
        }
        Field f = field(name);
        if (f.kind == 'N') {
            BigDecimal b = value instanceof Number ? new BigDecimal(value.toString())
                    : parseNumber(String.valueOf(value), name);
            values.put(name, fitNumber(f, b, false));
        } else {
            move(name, value == null ? "" : value.toString());
        }
    }

    public List<String> unknown(Collection<String> names) {
        List<String> out = new ArrayList<>();
        for (String n : names) if (!layout.fields.containsKey(n)) out.add(n);
        return out;
    }

    public Map<String, Object> changed() {
        Map<String, Object> out = new LinkedHashMap<>();
        for (Map.Entry<String, Object> e : values.entrySet()) {
            if (!Objects.equals(e.getValue(), initialValues.get(e.getKey()))) out.put(e.getKey(), e.getValue());
        }
        return out;
    }

    public Map<String, Object> snapshot(Collection<String> names) {
        Map<String, Object> out = new LinkedHashMap<>();
        for (String n : names) if (has(n)) out.put(n, val(n));
        return out;
    }

